from datetime import datetime, timezone

from feedgen.feed import FeedGenerator

from .config import settings
from .db import Site


def build_rss(site: Site, feed_url: str) -> bytes:
    fg = FeedGenerator()
    fg.id(feed_url)
    fg.title(site.name)
    # feedgen uses the last link as the RSS <channel><link>, so add "self" first.
    fg.link(href=feed_url, rel="self")
    fg.link(href=site.url, rel="alternate")
    fg.description(site.description or f"Updates from {site.url} generated by rssifi")
    fg.generator("rssifi")
    fg.ttl(_ttl_minutes(site))
    if site.last_success_at:
        fg.lastBuildDate(_aware(site.last_success_at))

    # feedgen prepends entries, so add oldest first to keep newest at the top.
    for item in reversed(site.items[: settings.max_items_per_feed]):
        fe = fg.add_entry()
        fe.id(item.guid)
        fe.guid(item.guid, permalink=item.guid == item.link)
        fe.title(item.title)
        fe.link(href=item.link)
        if item.summary:
            fe.description(item.summary)
        fe.pubDate(_aware(item.first_seen_at))
    return fg.rss_str(pretty=True)


def _ttl_minutes(site: Site) -> int:
    if site.schedule_type == "interval":
        return max(1, site.interval_minutes)
    return 60


def _aware(dt: datetime) -> datetime:
    # SQLite drops tzinfo; everything is stored in UTC.
    return dt if dt.tzinfo else dt.replace(tzinfo=timezone.utc)
